function renderPathologyTests(targetId) {
  const target = document.getElementById(targetId);
  if (!target) return;

  const columns = [
    ["sl", "Sl #"],
    ["code", "Test Code"],
    ["name", "Test Name"],
    ["category", "Category"],
    ["vials", "Vials"],
    ["reportDays", "Report Days"],
    ["mrp", "MRP"],
    ["extra", "Extra"]
  ];

  const table = document.createElement("table");
  table.className = "pathology-test-table";

  const thead = document.createElement("thead");
  const header = document.createElement("tr");

  columns.forEach(([, label]) => {
    const th = document.createElement("th");
    th.textContent = label;
    header.appendChild(th);
  });

  thead.appendChild(header);
  table.appendChild(thead);

  const tbody = document.createElement("tbody");

  pathologyTests.forEach((test, index) => {
    const tr = document.createElement("tr");

    columns.forEach(([key]) => {
      const td = document.createElement("td");

      if (key === "extra") {
        const input = document.createElement("input");
        input.type = "text";
        input.className = "pathology-extra-input";
        input.value = test.extra;
        input.dataset.row = String(index);
        input.setAttribute("aria-label", "Extra value for " + test.name);
        td.appendChild(input);
      } else {
        td.textContent = test[key];
      }

      tr.appendChild(td);
    });

    tbody.appendChild(tr);
  });

  table.appendChild(tbody);
  target.replaceChildren(table);
      }
